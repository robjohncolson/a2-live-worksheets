#!/usr/bin/env node
// Topic Assessment audit. data/a2-topic-assessments.json is authored (docs/a2-fast-lesson-spec.md,
// section 7): every Savvas Topic Assessment item of Topics 1-7 mapped to its lesson and Example,
// with DOK, Skills Review code, SAT and Precalculus relevance, the district form's status and the
// per-lesson re-ranking under R1. This script renders it as docs/a2-topic-assessment-audit.md,
// reading data/a2-lesson-targets.json (plan ratings) and content/a2/lesson-prep.json (kept
// Examples) so the doc says which items a kept Example covers, which sit under a cut Example and
// which fall in lessons that have no fast lesson. `--check` verifies the doc is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const PATHS = {
  data: 'data/a2-topic-assessments.json',
  targets: 'data/a2-lesson-targets.json',
  prep: 'content/a2/lesson-prep.json',
  doc: 'docs/a2-topic-assessment-audit.md',
};

export function loadInputs(root = ROOT) {
  const read = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
  return { data: read(PATHS.data), targets: read(PATHS.targets), prep: read(PATHS.prep).lessons };
}

const cell = value => String(value ?? '').replace(/\|/g, '\\|').replace(/\s*\r?\n\s*/g, ' ').trim();
const list = values => (Array.isArray(values) && values.length ? values.join(', ') : '');

// Where an item stands for the fast lessons: kept (a kept Example teaches it), cut (only cut
// Examples teach it), none (no Example named), or no-lesson (the lesson has no fast packet).
export function coverage(item, prep) {
  const entry = prep[item.lesson];
  if (!entry) return 'no-lesson';
  const kept = new Set((entry.examples || []).filter(e => e && e.keep === true).map(e => e.n));
  const examples = Array.isArray(item.examples) ? item.examples : [];
  if (!examples.length) return 'none';
  return examples.some(n => kept.has(n)) ? 'kept' : 'cut';
}

export function renderAudit({ data, targets, prep }) {
  const plan = Object.fromEntries(targets.lessons.map(lesson => [lesson.key, lesson]));
  const out = [
    '# Topic Assessment audit: every Savvas item, its lesson and its Example',
    '',
    'Generated by `node scripts/build-a2-topic-assessment-audit.mjs` from `data/a2-topic-assessments.json`,',
    '`data/a2-lesson-targets.json` and `content/a2/lesson-prep.json`. Do not edit by hand.',
    '',
    cell(data.source),
    '',
    '**Coverage** says what the fast lessons do with an item: *kept* = a kept Example teaches it; *cut* = only a',
    'cut Example teaches it (the PLC can restore that Example); *none* = no single Example teaches it (Topic Review',
    'skill or mixed); *no fast lesson* = the lesson is skipped, later or unpublished in the year plan. SAT and',
    'Precalculus columns are the audit\'s judgment of what the department is likely to keep when it trims the',
    'Savvas form; the district form, when it arrives, replaces both columns.',
    '',
  ];
  const totals = { items: 0, kept: 0, cut: 0, none: 0, 'no-lesson': 0, dok3: 0 };
  const topics = Object.entries(data.topics || {}).sort((a, b) => Number(a[0]) - Number(b[0]));
  out.push('| Topic | Items | Covered by a kept Example | Under a cut Example | No Example | No fast lesson | DOK 3 items |');
  out.push('|---|---|---|---|---|---|---|');
  const perTopic = [];
  for (const [n, topic] of topics) {
    const items = topic.byItem || [];
    const counts = { items: items.length, kept: 0, cut: 0, none: 0, 'no-lesson': 0, dok3: items.filter(i => i.dok === 3).length };
    for (const item of items) counts[coverage(item, prep)] += 1;
    for (const key of Object.keys(totals)) totals[key] += counts[key];
    perTopic.push([n, topic, counts]);
    out.push(`| ${n} ${cell(topic.title)} | ${counts.items} | ${counts.kept} | ${counts.cut} | ${counts.none} | ${counts['no-lesson']} | ${counts.dok3} |`);
  }
  out.push(`| **All** | ${totals.items} | ${totals.kept} | ${totals.cut} | ${totals.none} | ${totals['no-lesson']} | ${totals.dok3} |`);
  out.push('');

  for (const [n, topic, counts] of perTopic) {
    const items = topic.byItem || [];
    out.push(`## Topic ${n}: ${cell(topic.title)}`, '');
    out.push(`Source: \`../Lesson_planning/${cell(topic.transcription)}\` (TE printed pages ${cell(topic.printed)}; Forms A and B, ${counts.items} items).`);
    if (topic.district) {
      const d = topic.district;
      out.push(`District form: ${cell(d.status)}${d.file ? ` (\`${cell(d.file)}\`)` : ''}${d.note ? `. ${cell(d.note)}` : ''}`);
    }
    if (topic.notes) out.push('', cell(topic.notes));
    out.push('');
    const dok = [1, 2, 3].map(level => [level, items.filter(i => i.dok === level).map(i => i.n)]);
    out.push('| DOK | Items | Count |', '|---|---|---|');
    for (const [level, ns] of dok) out.push(`| ${level} | ${ns.length ? ns.join(', ') : 'none'} | ${ns.length} |`);
    out.push('');

    // Items by lesson, in year-plan order, then any lesson the plan does not list.
    const lessonKeys = [...new Set([...targets.lessons.filter(l => l.topic === Number(n)).map(l => l.key), ...items.map(i => i.lesson)])];
    out.push('| Lesson | Plan | Items | Kept Example covers | Under a cut Example | No Example | Fast lesson |', '|---|---|---|---|---|---|---|');
    for (const key of lessonKeys) {
      const mine = items.filter(i => i.lesson === key);
      if (!mine.length && !plan[key]) continue;
      const cov = status => mine.filter(i => coverage(i, prep) === status).map(i => i.n);
      const entry = prep[key];
      const fast = entry ? `yes (keeps ${list((entry.examples || []).filter(e => e && e.keep).map(e => e.n)) || 'none'})` : 'no';
      out.push(`| ${key} | ${plan[key] ? plan[key].plan : 'not in the plan'} | ${list(mine.map(i => i.n)) || 'none'} | ${list(cov('kept'))} | ${list(cov('cut'))} | ${list(cov('none'))} | ${fast} |`);
    }
    out.push('');

    out.push('| Item | DOK | Skills | Lesson | Example | Form A asks | Key A | SAT | Precalc | District | Coverage |', '|---|---|---|---|---|---|---|---|---|---|---|');
    for (const item of items) {
      out.push(`| ${item.n} | ${item.dok} | ${list(item.skills)} | ${cell(item.lesson)} | ${list(item.examples) || '-'} | ${cell(item.formA)} | ${cell(item.keyA)} | ${cell(item.sat)} | ${cell(item.precalc)} | ${cell(item.district)} | ${coverage(item, prep)} |`);
    }
    out.push('');
    const notes = items.filter(i => i.note || i.satWhy || i.precalcWhy || i.districtNote);
    if (notes.length) {
      out.push('Item notes:', '');
      for (const item of notes) {
        const parts = [item.note, item.satWhy ? `SAT: ${item.satWhy}` : '', item.precalcWhy ? `Precalculus: ${item.precalcWhy}` : '', item.districtNote ? `District: ${item.districtNote}` : ''].filter(Boolean);
        out.push(`- Item ${item.n} (${cell(item.lesson)}): ${parts.map(cell).join(' ')}`);
      }
      out.push('');
    }
    const lessons = Object.entries(topic.lessons || {});
    if (lessons.length) {
      out.push('### Re-ranking under R1 (topic items outrank quiz items)', '');
      out.push('| Lesson | Topic items | Kept before | Kept after | Changed | Why |', '|---|---|---|---|---|---|');
      for (const [key, rec] of lessons) {
        out.push(`| ${key} | ${list(rec.items)} | ${list(rec.currentKept)} | ${list(rec.recommendedKept)} | ${rec.change ? 'yes' : 'no'} | ${cell(rec.why)} |`);
      }
      out.push('');
    }
  }
  return out.join('\n') + '\n';
}

function main(argv) {
  const check = argv.includes('--check');
  const inputs = loadInputs();
  const rendered = renderAudit(inputs);
  const path = resolve(ROOT, PATHS.doc);
  let current = null;
  try { current = readFileSync(path, 'utf8'); } catch { current = null; }
  if (check) {
    if (current === rendered) { console.log(`${PATHS.doc} is current.`); return 0; }
    console.error(`${PATHS.doc} is stale; run node scripts/build-a2-topic-assessment-audit.mjs`);
    return 1;
  }
  if (current === rendered) { console.log(`${PATHS.doc} unchanged.`); return 0; }
  writeFileSync(path, rendered);
  console.log(`written ${PATHS.doc} (${rendered.split('\n').length} lines)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
