import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
export function buildBootstrapSql() {
  const directory = resolve(root, 'roster-server/migrations');
  const files = readdirSync(directory).filter(name => /^\d+.*\.sql$/.test(name)).sort();
  const migrations = files.map(name => {
    const source = readFileSync(resolve(directory, name), 'utf8').replace(/\r\n/g, '\n');
    const digest = createHash('sha256').update(source).digest('hex');
    // Pin function execution as well as creation: REST has its own search path.
    const sql = source.replace(/\bpublic\./gi, 'a2.')
      .replace(/\blanguage\s+(sql|plpgsql)\b/gi, '$& SET search_path TO a2');
    return `-- ${name}\nDO $migration$\nBEGIN
  IF EXISTS (SELECT 1 FROM a2._bootstrap_migrations WHERE name = '${name}' AND digest <> '${digest}') THEN
    RAISE EXCEPTION 'Applied migration ${name} changed; author a new migration instead';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM a2._bootstrap_migrations WHERE name = '${name}') THEN
${sql.trim()}
    INSERT INTO a2._bootstrap_migrations(name, digest) VALUES ('${name}', '${digest}');
  END IF;
END;
$migration$;`;
  });
  return `-- Generated by node scripts/build-bootstrap-sql.mjs. Do not edit this file.
-- Source of truth: roster-server/migrations/*.sql (${files.length} migrations).
-- Requires the existing Supabase anon, authenticated and service_role roles.
-- Ledger guards avoid replaying old constraints over newer, populated A2 data.
CREATE SCHEMA IF NOT EXISTS a2;
SET search_path TO a2;
BEGIN;
CREATE TABLE IF NOT EXISTS a2._bootstrap_migrations (
  name text PRIMARY KEY,
  digest text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE a2._bootstrap_migrations ENABLE ROW LEVEL SECURITY;

${migrations.join('\n\n')}

-- Tables, views and RPCs belong to a2. Only the server role may use them.
REVOKE ALL ON ALL TABLES IN SCHEMA a2 FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA a2 FROM anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA a2 FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA a2 TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA a2 TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA a2 TO service_role;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA a2 TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA a2 GRANT ALL ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA a2 GRANT ALL ON SEQUENCES TO service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA a2 GRANT EXECUTE ON FUNCTIONS TO service_role;
-- PostgreSQL's built-in PUBLIC function grant cannot be removed per schema
-- with default privileges. Future migrations must explicitly revoke it too.
NOTIFY pgrst, 'reload schema';
COMMIT;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(root, 'deploy'), { recursive: true });
  writeFileSync(resolve(root, 'deploy/supabase_a2_bootstrap.sql'), buildBootstrapSql());
}
