#!/usr/bin/env node
// Resolves data/a2-lesson-skills.json (IXL skills per lesson, authored by IXL shortcut
// code) against data/ixl-algebra2-skills.json and writes:
//   content/a2/lesson-skills.json     every mapped lesson -> [{ code, directoryId, name, url, level }]
//                                     (the Desk shows these on published AND planned calendar cells)
//   content/a2/lessons.json           supportingSkills of each published lesson, same order
//                                     ({ name, url, level } plus code/directoryId when known)
//
//   node scripts/build-a2-lesson-skills.mjs            # rewrites both files
//   node scripts/build-a2-lesson-skills.mjs --check    # exits 1 when either committed file is stale
//
// After a run: node scripts/sync-server-shared.mjs, build-a2-roadmap-data.mjs,
// build-a2-work-manifest.mjs and bump-build.mjs (CLAUDE.md).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LEVELS = ['prereq', 'core'];

export function skillUrl(skill) {
  if (skill.url) return skill.url;
  const slug = skill.skill.toLowerCase().replace(/'/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return 'https://www.ixl.com/math/algebra-2/' + slug;
}

export function resolveLessonSkills({ authored, map }) {
  const byCode = Object.fromEntries(map.skills.map(skill => [skill.code, skill]));
  const lessons = {};
  for (const [key, entries] of Object.entries(authored.lessons)) {
    lessons[key] = entries.map(entry => {
      if (!LEVELS.includes(entry.level)) throw new Error(`${key}: level must be prereq or core`);
      if (entry.code) {
        const skill = byCode[entry.code];
        if (!skill) throw new Error(`${key}: unknown IXL code ${entry.code}`);
        return { code: skill.code, directoryId: skill.directoryId, name: skill.skill, url: skillUrl(skill), level: entry.level };
      }
      if (!entry.name || !entry.url) throw new Error(`${key}: a literal skill needs name and url`);
      return { name: entry.name, url: entry.url, level: entry.level };
    });
    const firstCore = lessons[key].findIndex(skill => skill.level === 'core');
    if (firstCore >= 0 && lessons[key].slice(firstCore).some(skill => skill.level === 'prereq')) throw new Error(`${key}: prereq skills must come first`);
  }
  return lessons;
}

export function applyToPublished(published, lessons) {
  return published.map(lesson => lessons[lesson.key]
    ? { ...lesson, supportingSkills: lessons[lesson.key].map(({ name, url, level, code, directoryId }) => ({ name, url, level, ...(code ? { code, directoryId } : {}) })) }
    : lesson);
}

export function loadInputs() {
  return {
    authored: JSON.parse(readFileSync(resolve(ROOT, 'data/a2-lesson-skills.json'), 'utf8')),
    map: JSON.parse(readFileSync(resolve(ROOT, 'data/ixl-algebra2-skills.json'), 'utf8')),
    published: JSON.parse(readFileSync(resolve(ROOT, 'content/a2/lessons.json'), 'utf8')),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const { authored, map, published } = loadInputs();
  const lessons = resolveLessonSkills({ authored, map });
  const skillsJson = JSON.stringify({ about: 'Generated by scripts/build-a2-lesson-skills.mjs from data/a2-lesson-skills.json; do not edit.', lessons }, null, 2) + '\n';
  const lessonsJson = JSON.stringify(applyToPublished(published, lessons), null, 2) + '\n';
  const currentSkills = (() => { try { return readFileSync(resolve(ROOT, 'content/a2/lesson-skills.json'), 'utf8'); } catch (_) { return ''; } })();
  const currentLessons = readFileSync(resolve(ROOT, 'content/a2/lessons.json'), 'utf8');
  if (process.argv.includes('--check')) {
    if (currentSkills !== skillsJson || currentLessons !== lessonsJson) { console.error('a2 lesson skills are stale; run node scripts/build-a2-lesson-skills.mjs'); process.exit(1); }
    console.log('a2 lesson skills are current');
  } else {
    writeFileSync(resolve(ROOT, 'content/a2/lesson-skills.json'), skillsJson);
    if (currentLessons !== lessonsJson) writeFileSync(resolve(ROOT, 'content/a2/lessons.json'), lessonsJson);
    console.log(`content/a2/lesson-skills.json: ${Object.keys(lessons).length} lessons, ${Object.values(lessons).flat().length} skills; lessons.json ${currentLessons !== lessonsJson ? 'updated' : 'unchanged'}`);
  }
}
